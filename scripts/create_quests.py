def load_json(path: Path) -> dict[str, object]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise TypeError(f"JSON 최상위 값이 객체가 아닙니다: {path}")
    return value


def write_json(path: Path, value: object) -> None:
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def restore_layout(source: object, translated: object) -> object:
    """번역문의 | 표식을 원문의 줄바꿈 배열로 치환한다."""
    if isinstance(source, str) and isinstance(translated, str):
        separators = re.findall(r"(?:\\n)+", source)
        parts = translated.split("|")
        if len(parts) != len(separators) + 1:
            raise ValueError(
                f"줄바꿈 구획 수 불일치: source={source!r}, translated={translated!r}"
            )
        result = parts[0]
        for separator, part in zip(separators, parts[1:]):
            result += separator + part
        return result
    if isinstance(source, list) and isinstance(translated, list):
        if len(source) != len(translated):
            raise ValueError("퀘스트 설명 배열 길이가 다릅니다.")
        return [restore_layout(left, right) for left, right in zip(source, translated)]
    raise TypeError("퀘스트 설명 자료형이 원문과 다릅니다.")


def restore_format_codes(source: object, translated: object) -> object:
    """번역 중 생략된 색상 코드를 문장 끝의 무표시 구간에 보존한다."""
    if isinstance(source, str) and isinstance(translated, str):
        pattern = re.compile(r"[§&][0-9A-FK-ORa-fk-or]")
        source_codes = pattern.findall(source)
        target_counts = Counter(pattern.findall(translated))
        source_counts = Counter(source_codes)
        extras = target_counts - source_counts
        if extras:
            raise ValueError(f"원문에 없는 색상 코드가 있습니다: {dict(extras)}")
        missing = source_counts - target_counts
        suffix = ""
        for code in source_codes:
            if missing[code] > 0:
                suffix += code
                missing[code] -= 1
        return translated + suffix
    if isinstance(source, list) and isinstance(translated, list):
        return [
            restore_format_codes(left, right) for left, right in zip(source, translated)
        ]
    raise TypeError("퀘스트 설명 자료형이 원문과 다릅니다.")


def normalize() -> dict[str, object]:
    translations = {
        "create": {**CREATE_TITLES, **CREATE_SUBTITLES, **CREATE_DESCRIPTIONS},
        "related": RELATED_TRANSLATIONS,
    }
    rows = []
    for group, overrides in translations.items():
        root = WORK_ROOT / group
        english = load_json(root / "en_us.json")
        korean = load_json(root / "ko_kr.json")
        unknown = sorted(set(overrides) - set(english))
        if unknown:
            raise KeyError(f"{group} 원문에 없는 키: {unknown}")
        for key, value in overrides.items():
            if key.endswith(".quest_desc"):
                value = restore_layout(english[key], value)
                value = restore_format_codes(english[key], value)
            errors = validate_value(key, english[key], value)
            if errors:
                raise ValueError("; ".join(errors))
            korean[key] = value
        write_json(root / "ko_kr.json", korean)
        rows.append(
            {
                "group": group,
                "keys": len(english),
                "reviewed": len(overrides),
                "remaining": len(set(english) - set(overrides)),
            }
        )
    return {"groups": rows}


def verify() -> tuple[dict[str, object], list[str]]:
    errors = []
    rows = []
    allowed_originals = {"&6&lCreate&r 1.21", "&6&lCreate&r", "&6&lCreate"}
    for group in ("create", "related"):
        root = WORK_ROOT / group
        english = load_json(root / "en_us.json")
        korean = load_json(root / "ko_kr.json")
        if list(english) != list(korean):
            errors.append(f"키 또는 순서 불일치: {group}")
            continue
        untranslated = []
        for key, source in english.items():
            target = korean[key]
            errors.extend(validate_value(key, source, target))
            if source == target and source not in allowed_originals:
                untranslated.append(key)
        if untranslated:
            errors.append(f"미번역: {group}:{untranslated[:30]}")
        rows.append(
            {"group": group, "keys": len(english), "untranslated": len(untranslated)}
        )
    report = {
        "groups": rows,
        "errors": errors,
        "status": "complete" if not errors else "incomplete",
    }
    write_json(WORK_ROOT.parent / "quest_validation.json", report)
    return report, errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("normalize", "verify"))
    args = parser.parse_args()
    if args.command == "normalize":
        report = normalize()
        errors = []
    else:
        report, errors = verify()
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 1 if errors else 0


