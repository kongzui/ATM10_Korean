def translate(key: str, source: object) -> str:
    """현재 원문 키에 대응하는 검수된 표시 문구를 반환한다."""
    if key in DESCRIPTIONS:
        return DESCRIPTIONS[key]
    if key.endswith(".title") and isinstance(source, str) and source in TITLE_VALUES:
        return TITLE_VALUES[source]
    raise KeyError(f"수동 번역이 없는 The Aether 퀘스트 키: {key} = {source!r}")
